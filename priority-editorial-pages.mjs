const renderPage = {eggs,'ask-shop':askShop,thanks,editorial};
export function priorityEditorialPage({r,typeset}) {
  const item = entries[r.slug];
  if (!item) return null;
  const t = typeset;
  return {
    lead: t(item.lead),
    body: '<div class="priority-editorial">'+renderPage[r.slug](t)+'</div>',
    related: '<aside class="priority-editorial-related" aria-label="次に読む">'+head('もう少し読みたいときに',t)
      +item.related.map(([slug,label,why])=>'<p>'+local(slug,label,t)+'<span>'+t(why)+'</span></p>').join('')+'</aside>'
  };
}
export function priorityEditorialSearchText(row, plain) {
  const page = priorityEditorialPage({r: row, typeset: plain});
  return page ? [page.lead, page.body.replace(/<[^>]*>/g,' '), page.related.replace(/<[^>]*>/g,' ')].join(' ').replace(/\s+/g,' ').trim() : '';
}
